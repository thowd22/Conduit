/// The pinned FreeType, built from source. The source list and the flags are
/// the ones the pinned Ghostty tree's `pkg/freetype/build.zig` uses with its
/// `enable-libpng` option on: libpng (and the zlib it needs) is built from the
/// same pinned sources, because colour emoji fonts store their glyphs as PNG
/// strikes (TASK-39). FreeType keeps its own internal zlib copy for gzip-
/// compressed fonts rather than the system one.
fn freetypeLib(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) !*std.Build.Step.Compile {
    const upstream = b.dependency("freetype", .{ .target = target, .optimize = optimize });
    const lib = b.addLibrary(.{
        .name = "freetype",
        .root_module = b.createModule(.{
            .target = target,
            .optimize = optimize,
            .link_libc = true,
        }),
        .linkage = .static,
    });

    var flags: std.ArrayList([]const u8) = .empty;
    defer flags.deinit(b.allocator);
    try flags.appendSlice(b.allocator, &.{
        "-DFT2_BUILD_LIBRARY",
        "-fno-sanitize=undefined",
        "-DFT_CONFIG_OPTION_USE_PNG=1",
    });
    if (target.result.os.tag != .windows) {
        try flags.appendSlice(b.allocator, &.{
            "-DHAVE_UNISTD_H",
            "-DHAVE_FCNTL_H",
        });
    }

    const zlib = try zlibLib(b, target, optimize);
    const png = try libpngLib(b, target, optimize, zlib);
    lib.root_module.linkLibrary(png.lib);
    lib.root_module.linkLibrary(zlib);
    lib.root_module.addIncludePath(png.config);
    lib.root_module.addIncludePath(png.include);
    lib.root_module.addIncludePath(b.dependency("zlib", .{}).path(""));

    lib.root_module.addIncludePath(upstream.path("include"));
    lib.root_module.addCSourceFiles(.{
        .root = upstream.path(""),
        .files = freetype_srcs,
        .flags = flags.items,
    });

    // `src/svg/svg.c` compiles to nothing without `FT_CONFIG_OPTION_SVG`, but `ftinit.c` still
    // refers to the SVG renderer class, so leaving it out is a link error.
    lib.root_module.addCSourceFile(.{
        .file = upstream.path("src/svg/svg.c"),
        .flags = flags.items,
    });

    // `ftsystem.c` and `ftdebug.c` are the two files upstream keeps per
    // platform. Getting them wrong builds a library that reads font files
    // with the wrong file API, so they are chosen by OS rather than left to
    // the generic copy.
    switch (target.result.os.tag) {
        .linux => {
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("builds/unix/ftsystem.c"),
                .flags = flags.items,
            });
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("src/base/ftdebug.c"),
                .flags = flags.items,
            });
        },
        .windows => {
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("builds/windows/ftsystem.c"),
                .flags = flags.items,
            });
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("builds/windows/ftdebug.c"),
                .flags = flags.items,
            });
            lib.root_module.addWin32ResourceFile(.{ .file = upstream.path("src/base/ftver.rc") });
        },
        else => {
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("src/base/ftsystem.c"),
                .flags = flags.items,
            });
            lib.root_module.addCSourceFile(.{
                .file = upstream.path("src/base/ftdebug.c"),
                .flags = flags.items,
            });
        },
    }

    return lib;
}

/// The pinned HarfBuzz, built from its upstream amalgamation. `hb-ft` is
/// compiled in and FreeType linked, because the shaper reads glyph data
/// through the same face the rasteriser rasterised with.
fn harfbuzzLib(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    ft_lib: *std.Build.Step.Compile,
) !*std.Build.Step.Compile {
    const upstream = b.dependency("harfbuzz", .{ .target = target, .optimize = optimize });
    const lib = b.addLibrary(.{
        .name = "harfbuzz",
        .root_module = b.createModule(.{
            .target = target,
            .optimize = optimize,
            .link_libc = true,
            // On MSVC, linking Zig's libc++ puts Zig's bundled C++ headers
            // ahead of the SDK's own and the two sets conflict. The SDK
            // headers are on the include path already, so libc++ is only
            // linked where there is no SDK C++ runtime to conflict with.
            .link_libcpp = target.result.abi != .msvc,
        }),
        .linkage = .static,
    });
    lib.root_module.linkLibrary(ft_lib);

    var flags: std.ArrayList([]const u8) = .empty;
    defer flags.deinit(b.allocator);
    try flags.appendSlice(b.allocator, &.{
        "-DHAVE_STDBOOL_H",
        "-DHAVE_FREETYPE=1",
        // The FreeType this build pins is new enough for the variable-font
        // and transform entry points HarfBuzz probes for at configure time.
        "-DHAVE_FT_GET_VAR_BLEND_COORDINATES=1",
        "-DHAVE_FT_SET_VAR_BLEND_COORDINATES=1",
        "-DHAVE_FT_DONE_MM_VAR=1",
        "-DHAVE_FT_GET_TRANSFORM=1",
    });
    if (target.result.os.tag != .windows) {
        try flags.appendSlice(b.allocator, &.{
            "-DHAVE_UNISTD_H",
            "-DHAVE_SYS_MMAN_H",
            "-DHAVE_PTHREAD=1",
        });
    }
    if (target.result.abi == .msvc) {
        // Zig's ubsan runtime cannot be bundled into a static archive that an
        // external linker consumes (LNK4229), so the archive would be left
        // with unresolved `__ubsan_handle_*` symbols.
        try flags.appendSlice(b.allocator, &.{
            "-fno-sanitize=undefined",
            "-fno-sanitize-trap=undefined",
        });
    }

    lib.root_module.addIncludePath(upstream.path("src"));
    // `hb-ft.h` includes `ft2build.h`, so HarfBuzz is built against FreeType's headers as well as
    // against the FreeType library.
    lib.root_module.addIncludePath(
        b.dependency("freetype", .{ .target = target, .optimize = optimize }).path("include"),
    );
    lib.root_module.addCSourceFile(.{
        .file = upstream.path("src/harfbuzz.cc"),
        .flags = flags.items,
    });

    return lib;
}

/// The Conduit-owned FreeType and HarfBuzz seam: both libraries' public headers,
/// translated together.
///
/// One step, not two, because `hb-ft.h` takes an `FT_Face` and returns a HarfBuzz
/// font built from it: translating the headers separately would give Conduit two
/// unrelated Zig types for the same C struct, and passing a face from one to the
/// other would not compile.
fn fontSeam(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const seam = std.Build.Step.TranslateC.create(b, .{
        .root_source_file = b.addWriteFiles().add("font.h", font_c_header),
        .target = target,
        .optimize = optimize,
    });
    seam.addIncludePath(
        b.dependency("freetype", .{ .target = target, .optimize = optimize }).path("include"),
    );
    seam.addIncludePath(
        b.dependency("harfbuzz", .{ .target = target, .optimize = optimize }).path("src"),
    );
    return seam.createModule();
}

