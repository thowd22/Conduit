/// Prove the pinned SDL3 package resolves, translates, links and runs on this
/// toolchain, by building and running a generated source against the same seam
/// `platform` uses. `SDL_GetVersion` needs no window and no display.
///
/// This is not part of the default build: SDL3 is a large C library, and nothing
/// imports it until `platform` does. It stays because decision-2 rests on SDL3
/// working on Zig 0.16, and a pin that stops linking should fail here rather than
/// in whichever task first opens a window.
fn addSdlCheck(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) void {
    const sdl_lib = sdlLib(b, target, optimize);
    const mod = b.createModule(.{
        .root_source_file = b.addWriteFiles().add("sdl_check.zig",
            \\const std = @import("std");
            \\const sdl = @import("sdl");
            \\
            \\pub fn main(init: std.process.Init) !void {
            \\    const encoded = sdl.SDL_GetVersion();
            \\    var buf: [128]u8 = undefined;
            \\    var out = std.Io.File.stdout().writerStreaming(init.io, &buf);
            \\    try out.interface.print("SDL3 seam linked: {d}.{d}.{d}\n", .{
            \\        sdl.SDL_VERSIONNUM_MAJOR(encoded),
            \\        sdl.SDL_VERSIONNUM_MINOR(encoded),
            \\        sdl.SDL_VERSIONNUM_MICRO(encoded),
            \\    });
            \\    try out.interface.flush();
            \\}
        ),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    mod.addImport("sdl", sdlSeam(b, target, optimize, sdl_lib));
    mod.linkLibrary(sdl_lib);

    const exe = b.addExecutable(.{ .name = "conduit-sdl-check", .root_module = mod });
    b.step("sdl-check", "Build and run the SDL3 seam, proving the pin on this toolchain")
        .dependOn(&b.addRunArtifact(exe).step);
}

/// Prove the pinned font stack resolves, loads, shapes, rasterises and caches, by
/// running a generated program against the same `font` module the app imports:
/// a configured family resolved from the system font directories, the bundled
/// face standing in for one that is not installed, the cell metrics of both, and
/// a glyph read back out of the atlas before and after the cache evicts it.
///
/// It is not part of the default build because most of its output depends on the
/// machine's fonts: CI runners install none, so `zig build font-check` is a
/// developer and release-machine step, while the unconditional half of the same
/// behaviour lives in the `font` module's own tests.
fn addFontCheck(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    font: *std.Build.Module,
    wiring: FontWiring,
) void {
    const mod = b.createModule(.{
        .root_source_file = b.addWriteFiles().add("font_check.zig",
            \\const std = @import("std");
            \\const font = @import("font");
            \\const c = @import("font-c");
            \\
            \\/// An FNV-1a hash of the atlas bytes, so a glyph's pixels can be compared
            \\/// across an eviction without printing a screenful of coverage.
            \\fn digest(bytes: []const u8) u64 {
            \\    var hash: u64 = 14695981039346656037;
            \\    for (bytes) |byte| {
            \\        hash ^= byte;
            \\        hash = hash *% 1099511628211;
            \\    }
            \\    return hash;
            \\}
            \\
            \\pub fn main(init: std.process.Init) !void {
            \\    const gpa = init.gpa;
            \\    const home = init.environ_map.get("HOME");
            \\    var buf: [4096]u8 = undefined;
            \\    var out_file = std.Io.File.stdout().writerStreaming(init.io, &buf);
            \\    const out = &out_file.interface;
            \\    defer out_file.interface.flush() catch {};
            \\
            \\    try out.print("vendored HarfBuzz: {s}\n", .{c.hb_version_string()});
            \\
            \\    const directories = try font.systemFontDirectories(gpa, home);
            \\    defer {
            \\        for (directories) |directory| gpa.free(directory);
            \\        gpa.free(directories);
            \\    }
            \\    var catalog = try font.Catalog.scan(init.io, gpa, directories);
            \\    defer catalog.deinit();
            \\    try out.print("scanned {d} font files across {d} system directories\n", .{
            \\        catalog.files.items.len,
            \\        directories.len,
            \\    });
            \\    if (catalog.findFamily("JetBrains Mono")) |found| {
            \\        try out.print("family 'JetBrains Mono' -> {s} ({s} {s})\n", .{
            \\            found.path,
            \\            found.family,
            \\            found.style,
            \\        });
            \\    } else {
            \\        try out.writeAll("family 'JetBrains Mono' is not installed here\n");
            \\    }
            \\    try out.print("family 'Conduit Font That Does Not Exist' -> {s}\n", .{
            \\        if (catalog.findFamily("Conduit Font That Does Not Exist")) |_| "found" else "not found",
            \\    });
            \\
            \\    var resolved = try font.Manager.init(gpa, init.io, .{
            \\        .family = "JetBrains Mono",
            \\        .size = try font.Size.init(14, 1.0),
            \\        .home_dir = home,
            \\    });
            \\    defer resolved.deinit();
            \\    try out.print("resolved: family={s} fallback={} source={s}\n", .{
            \\        resolved.familyName(),
            \\        resolved.isFallback(),
            \\        resolved.sourcePath(),
            \\    });
            \\    try printMetrics(out, "resolved 14px", resolved.metrics());
            \\
            \\    var fallback = try font.Manager.init(gpa, init.io, .{
            \\        .family = "Conduit Font That Does Not Exist",
            \\        .size = try font.Size.init(14, 1.0),
            \\        .home_dir = home,
            \\    });
            \\    defer fallback.deinit();
            \\    try out.print("fallback: family={s} fallback={} source={s}\n", .{
            \\        fallback.familyName(),
            \\        fallback.isFallback(),
            \\        fallback.sourcePath(),
            \\    });
            \\    try printMetrics(out, "fallback 14px", fallback.metrics());
            \\
            \\    // The same bundled face at twice the pixels, to show the metrics come from the face
            \\    // and scale with the size rather than being constants.
            \\    var larger = try font.Manager.init(gpa, init.io, .{
            \\        .family = "Conduit Font That Does Not Exist",
            \\        .size = try font.Size.init(28, 1.0),
            \\        .home_dir = home,
            \\    });
            \\    defer larger.deinit();
            \\    try printMetrics(out, "fallback 28px", larger.metrics());
            \\
            \\    // A run of text through the shaper.
            \\    var run: std.ArrayList(font.ShapedGlyph) = .empty;
            \\    defer run.deinit(gpa);
            \\    try resolved.shape("conduit", &run);
            \\    try out.print("shaped 'conduit' into {d} glyphs:", .{run.items.len});
            \\    for (run.items) |glyph| {
            \\        try out.print(" gid={d}@{d} adv={d:.2}", .{
            \\            glyph.glyph_index,
            \\            glyph.cluster,
            \\            glyph.x_advance_px,
            \\        });
            \\    }
            \\    try out.writeByte('\n');
            \\
            \\    // The cache: rasterise a glyph, ask again, then overflow the atlas
            \\    // and ask a third time. The digest is the glyph's real pixels.
            \\    var cached = try font.Manager.init(gpa, init.io, .{
            \\        .family = "JetBrains Mono",
            \\        .size = try font.Size.init(20, 1.0),
            \\        .home_dir = home,
            \\        .atlas_width_px = 24,
            \\        .atlas_height_px = 24,
            \\    });
            \\    defer cached.deinit();
            \\
            \\    const watched = cached.glyphIndex('g');
            \\    const first = try cached.glyph(watched);
            \\    var first_pixels = try gpa.alloc(u8, @as(usize, first.rect.width) * first.rect.height);
            \\    defer gpa.free(first_pixels);
            \\    const first_len = cached.atlas.copyInto(first, first_pixels);
            \\    try out.print("glyph 'g': gid={d} {d}x{d}px at ({d},{d}) bearing=({d},{d}) advance={d}px digest=0x{x}\n", .{
            \\        watched,
            \\        first.rect.width,
            \\        first.rect.height,
            \\        first.rect.x,
            \\        first.rect.y,
            \\        first.bearing_x_px,
            \\        first.bearing_y_px,
            \\        first.advance_px,
            \\        digest(first_pixels[0..first_len]),
            \\    });
            \\
            \\    _ = try cached.glyph(watched);
            \\    try out.print("second request: hits={d} misses={d} insertions={d} evictions={d}\n", .{
            \\        cached.atlas.stats.hits,
            \\        cached.atlas.stats.misses,
            \\        cached.atlas.stats.insertions,
            \\        cached.atlas.stats.evictions,
            \\    });
            \\
            \\    var codepoint: u21 = '!';
            \\    while (codepoint <= '~' and cached.atlas.isLive(first)) : (codepoint += 1) {
            \\        if (codepoint == 'g') continue;
            \\        _ = cached.glyph(cached.glyphIndex(codepoint)) catch continue;
            \\    }
            \\    try out.print("after filling the atlas: live={} evictions={d}\n", .{
            \\        cached.atlas.isLive(first),
            \\        cached.atlas.stats.evictions,
            \\    });
            \\
            \\    const again = try cached.glyph(watched);
            \\    var after_pixels = try gpa.alloc(u8, first_pixels.len);
            \\    defer gpa.free(after_pixels);
            \\    const after_len = cached.atlas.copyInto(again, after_pixels);
            \\    try out.print("re-rasterised: {d}x{d}px digest=0x{x} identical={}\n", .{
            \\        again.rect.width,
            \\        again.rect.height,
            \\        digest(after_pixels[0..after_len]),
            \\        std.mem.eql(u8, first_pixels, after_pixels),
            \\    });
            \\}
            \\
            \\fn printMetrics(out: *std.Io.Writer, label: []const u8, metrics: font.Metrics) !void {
            \\    try out.print(
            \\        "metrics {s}: cell {d}x{d}px baseline {d}px ascent {d}px descent {d}px\n",
            \\        .{ label, metrics.cell.width_px, metrics.cell.height_px, metrics.baseline_px, metrics.ascent_px, metrics.descent_px },
            \\    );
            \\}
        ),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .link_libcpp = if (target.result.abi == .msvc) null else true,
    });
    mod.addImport("font", font);
    mod.addImport("font-c", wiring.seam);
    mod.linkLibrary(wiring.freetype);
    mod.linkLibrary(wiring.harfbuzz);

    const exe = b.addExecutable(.{ .name = "conduit-font-check", .root_module = mod });
    b.step("font-check", "Resolve, load, shape and cache glyphs with the pinned font stack")
        .dependOn(&b.addRunArtifact(exe).step);
}

/// Run the unit tests of every Conduit module that exists. A module's tests live
/// in the module itself, so a module lands in `zig build test` as soon as its
/// file does, with nothing to restructure here.
fn addTests(
    b: *std.Build,
    wired: WiredModules,
    conduit_test: *std.Build.Module,
    e2e: *std.Build.Module,
) void {
    const test_step = b.step("test", "Run the unit tests of every module");
    for (modules, 0..) |spec, i| {
        const mod = wired[i] orelse continue;
        const unit_tests = b.addTest(.{
            .name = b.fmt("{s}-test", .{spec.name}),
            .root_module = mod,
        });
        test_step.dependOn(&b.addRunArtifact(unit_tests).step);
    }

    const conduit_test_tests = b.addTest(.{
        .name = "conduit-test-test",
        .root_module = conduit_test,
    });
    test_step.dependOn(&b.addRunArtifact(conduit_test_tests).step);

    const e2e_tests = b.addTest(.{
        .name = "conduit-e2e-test",
        .root_module = e2e,
    });
    test_step.dependOn(&b.addRunArtifact(e2e_tests).step);

    addBenchTests(b, test_step, wired);
}

/// The optimisation the benchmarks are built with: ReleaseSafe unless
/// `-Doptimize` or `--release` asked for a mode explicitly. A Debug Conduit
/// is never what a budget describes, so a plain `zig build bench` does not
/// measure one; `-Doptimize=Debug` still does when asked for by name.
fn benchOptimize(b: *std.Build, optimize: std.builtin.OptimizeMode) std.builtin.OptimizeMode {
    if (b.user_input_options.contains("optimize") or b.release_mode != .off) return optimize;
    return .ReleaseSafe;
}

/// TASK-67: `zig build bench` and `zig build bench-check`.
///
/// Each benchmark is its own executable so its process memory is its own; the
/// `conduit-bench` runner (`bench/runner.zig`) runs them, echoes their JSON
/// lines, writes `--json=<path>` and, for `bench-check`, enforces
/// `bench/budgets.zig`. When the benchmark mode differs from the main build's,
/// the modules, the third-party seams and the app are wired a second time at
/// that mode, so the startup benchmark launches an optimised `conduit` rather
/// than the installed Debug one. Nothing here joins the default install.
fn addBenchmarks(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    wired: WiredModules,
    exe: *std.Build.Step.Compile,
    conduit_test_exe: *std.Build.Step.Compile,
    build_options_module: *std.Build.Module,
) !void {
    const bench_optimize = benchOptimize(b, optimize);
    var bench_wired = wired;
    var bench_exe = exe;
    var bench_conduit_test = conduit_test_exe;
    if (bench_optimize != optimize) {
        bench_wired = wireConduitModules(b, target, bench_optimize);
        _ = try wireThirdPartySeams(b, target, bench_optimize, &bench_wired);
        bench_wired[moduleIndex("version")].?.addImport("build_options", build_options_module);
        const app = bench_wired[moduleIndex("app")].?;
        app.addImport("build_options", build_options_module);
        bench_exe = b.addExecutable(.{ .name = "conduit", .root_module = app });

        const conduit_test = b.createModule(.{
            .root_source_file = b.path("src/conduit_test.zig"),
            .target = target,
            .optimize = bench_optimize,
        });
        conduit_test.addImport("platform", bench_wired[moduleIndex("platform")].?);
        conduit_test.addImport("testdriver", bench_wired[moduleIndex("testdriver")].?);
        conduit_test.addImport("build_options", build_options_module);
        bench_conduit_test = b.addExecutable(.{ .name = "conduit-test", .root_module = conduit_test });
    }

    const zopengl = b.dependency("zopengl", .{}).module("root");
    const programs = [_]struct { name: []const u8, imports: []const []const u8 }{
        .{ .name = "throughput", .imports = &.{ "term", "render", "font", "platform" } },
        .{ .name = "frame", .imports = &.{ "term", "render", "font", "platform" } },
        .{ .name = "memory", .imports = &.{ "term", "session", "workspace" } },
        .{ .name = "startup", .imports = &.{} },
    };

    const runner_module = b.createModule(.{
        .root_source_file = b.path("bench/runner.zig"),
        .target = target,
        .optimize = bench_optimize,
    });
    const runner = b.addExecutable(.{ .name = "conduit-bench", .root_module = runner_module });

    const bench_run = b.addRunArtifact(runner);
    const check_run = b.addRunArtifact(runner);
    check_run.addArg("--check");
    for ([_]*std.Build.Step.Run{ bench_run, check_run }) |run| {
        // The results depend on the machine and the moment, never only on the
        // inputs, so the step is never cached.
        run.has_side_effects = true;
        run.addPrefixedArtifactArg("--conduit-test=", bench_conduit_test);
        run.addPrefixedArtifactArg("--conduit=", bench_exe);
    }

    for (programs) |program| {
        const module = b.createModule(.{
            .root_source_file = b.path(b.fmt("bench/{s}.zig", .{program.name})),
            .target = target,
            .optimize = bench_optimize,
            .link_libc = true,
        });
        for (program.imports) |name| module.addImport(name, bench_wired[moduleIndex(name)].?);
        module.addImport("zopengl", zopengl);
        const program_exe = b.addExecutable(.{
            .name = b.fmt("conduit-bench-{s}", .{program.name}),
            .root_module = module,
        });
        const prefix = b.fmt("--{s}=", .{program.name});
        bench_run.addPrefixedArtifactArg(prefix, program_exe);
        check_run.addPrefixedArtifactArg(prefix, program_exe);
    }
    if (b.args) |args| {
        bench_run.addArgs(args);
        check_run.addArgs(args);
    }

    b.step("bench", "Run the throughput, frame, memory and startup benchmarks (ReleaseSafe)")
        .dependOn(&bench_run.step);
    b.step("bench-check", "Run the benchmarks and fail when a budget in bench/budgets.zig is breached")
        .dependOn(&check_run.step);
}

/// The benchmark helpers' own unit tests join `zig build test`. They need no
/// display: the GPU helper's test only classifies renderer strings.
fn addBenchTests(b: *std.Build, test_step: *std.Build.Step, wired: WiredModules) void {
    const zopengl = b.dependency("zopengl", .{}).module("root");
    for ([_][]const u8{ "bench/common.zig", "bench/runner.zig", "bench/gpu.zig" }) |source| {
        const module = b.createModule(.{
            .root_source_file = b.path(source),
            .target = wired[moduleIndex("render")].?.resolved_target,
            .optimize = wired[moduleIndex("render")].?.optimize,
            .link_libc = true,
        });
        if (std.mem.eql(u8, source, "bench/gpu.zig")) {
            for ([_][]const u8{ "render", "font", "platform" }) |name| module.addImport(name, wired[moduleIndex(name)].?);
            module.addImport("zopengl", zopengl);
        }
        test_step.dependOn(&b.addRunArtifact(b.addTest(.{
            .name = b.fmt("bench-{s}-test", .{std.fs.path.stem(source)}),
            .root_module = module,
        })).step);
    }
}

/// The row of `modules` a module name occupies. Fails the build on a typo in a
/// module name or a dependency edge, at configure time rather than at compile.
fn moduleIndex(name: []const u8) usize {
    for (modules, 0..) |spec, i| {
        if (std.mem.eql(u8, spec.name, name)) return i;
    }
    fail("unknown Conduit module: {s}", .{name});
}

/// Whether `path`, relative to the repository root, is present.
fn sourceExists(b: *std.Build, path: []const u8) bool {
    b.build_root.handle.access(b.graph.io, path, .{}) catch |err| switch (err) {
        error.FileNotFound => return false,
        else => fail("cannot access '{s}': {s}", .{ path, @errorName(err) }),
    };
    return true;
}

/// Fail the build with a plain message. Every failure raised in this file is a
/// mistake in this file, not in the environment, so it is reported as one.
fn fail(comptime format: []const u8, args: anytype) noreturn {
    std.log.err(format, args);
    std.process.exit(1);
}
