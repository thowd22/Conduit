//! Conduit's build script.
//!
//! Two things live here: the module layout `CONDUIT.md` and `AGENTS.md` specify,
//! and the pinned third-party seams behind that layout. Dependencies point
//! downward — `ui` and `workspace` may use `term` and `render`, and `term`,
//! `pty` and `font` know nothing about workspaces, agents or UI.
//!
//! A module joins the build as soon as its source file exists: adding one is
//! adding a `ModuleSpec` row and a file, and nothing else here changes. A row
//! whose file is not written yet declares nothing, because Zig 0.16 hashes the
//! root source file of every declared import — so declaring a module that is
//! not there would be a broken build rather than a pending one.

const std = @import("std");
const builtin = @import("builtin");

/// One Conduit module: the file its root is declared in, and the Conduit
/// modules it may import.
const ModuleSpec = struct {
    name: []const u8,
    source_file: []const u8,
    deps: []const []const u8,
};

/// The module layout, ordered from the leaves upward so the dependency edges
/// read top to bottom.
const modules = [_]ModuleSpec{
    // Leaves. OS-specific code stops at these seams.
    .{ .name = "platform", .source_file = "src/platform.zig", .deps = &.{} },
    .{ .name = "pty", .source_file = "src/pty.zig", .deps = &.{} },
    .{ .name = "config", .source_file = "src/config.zig", .deps = &.{} },
    .{ .name = "font", .source_file = "src/font.zig", .deps = &.{} },
    .{ .name = "link", .source_file = "src/link.zig", .deps = &.{} },
    // TASK-65: the persisted workspace layout, its file and the restore plan.
    .{ .name = "state", .source_file = "src/state.zig", .deps = &.{} },
    // The stamped release version (`-Dversion=`), re-exported from the
    // generated `build_options` module so TASK-69.1's packages can prove it.
    .{ .name = "version", .source_file = "src/version.zig", .deps = &.{} },

    // Terminal engine (libghostty) and the GPU surface both renderers share.
    .{ .name = "theme", .source_file = "src/theme.zig", .deps = &.{"config"} },
    .{ .name = "term", .source_file = "src/term.zig", .deps = &.{"pty"} },
    .{ .name = "render", .source_file = "src/render.zig", .deps = &.{ "font", "platform", "term" } },

    // UI toolkit: primitives and the semantic tree, then input over them.
    .{ .name = "ui", .source_file = "src/ui.zig", .deps = &.{ "font", "render", "term", "theme" } },
    .{ .name = "input", .source_file = "src/input.zig", .deps = &.{ "platform", "term", "ui" } },
    .{ .name = "palette", .source_file = "src/palette.zig", .deps = &.{"input"} },
    // TASK-68: snapshots of the semantic tree served to platform
    // accessibility APIs (AT-SPI2 over D-Bus on Linux).
    .{ .name = "accessibility", .source_file = "src/accessibility.zig", .deps = &.{"ui"} },

    // A session owns a PTY and terminal state; a workspace owns sessions.
    .{ .name = "session", .source_file = "src/session.zig", .deps = &.{ "config", "pty", "term", "theme" } },
    .{ .name = "workspace", .source_file = "src/workspace.zig", .deps = &.{
        "config", "input", "pty", "render", "session", "state", "term", "theme", "ui",
    } },

    // Feature layers over the workspace, and the automation that drives them.
    .{ .name = "agent", .source_file = "src/agent.zig", .deps = &.{
        "config", "input", "session", "theme", "ui", "workspace",
    } },
    .{ .name = "backlog", .source_file = "src/backlog.zig", .deps = &.{
        "config", "input", "theme", "ui", "workspace",
    } },
    .{ .name = "testdriver", .source_file = "src/testdriver.zig", .deps = &.{
        "input", "render", "session", "ui", "workspace",
    } },

    // TASK-60: the token-scoped local control API for harnesses.
    .{ .name = "control", .source_file = "src/control.zig", .deps = &.{"platform"} },

    // The composition root. Its root file is the executable entry point.
    .{ .name = "app", .source_file = "src/main.zig", .deps = &.{
        "accessibility", "agent",   "backlog",  "config",  "control",    "font",      "input",
        "link",          "palette", "platform", "pty",     "render",     "session",   "state",
        "term",          "theme",   "ui",       "version", "testdriver", "workspace",
    } },
};

/// The build module of each entry in `modules`, in the same order, or `null`
/// when the module has no source file yet.
const WiredModules = [modules.len]?*std.Build.Module;

/// The C declaration the SDL3 seam translates. It is generated by the build so
/// the seam needs no committed header file of its own.
const sdl_c_header =
    \\#define SDL_MAIN_HANDLED
    \\#include <SDL3/SDL.h>
;

/// The only Oniguruma declarations terminal search may call. Keeping the C
/// dependency behind this generated seam makes the regex engine an
/// implementation detail of `term` rather than a project-wide import.
const oniguruma_c_header =
    \\#define ONIG_STATIC
    \\#include <oniguruma.h>
;

pub fn build(b: *std.Build) !void {
    const target = b.standardTargetOptions(.{ .default_target = defaultTargetQuery() });
    const optimize = b.standardOptimizeOption(.{});

    const wired = wireConduitModules(b, target, optimize);
    const font_wiring = try wireThirdPartySeams(b, target, optimize, &wired);

    // TASK-69.1: the release version, validated here so a malformed tag fails
    // at configure time, then stamped into every binary that reports it.
    const build_options = b.addOptions();
    build_options.addOption([:0]const u8, "version", resolveVersion(b));
    const build_options_module = build_options.createModule();
    if (wired[moduleIndex("version")]) |version_module| {
        version_module.addImport("build_options", build_options_module);
    }

    const app_spec = modules[moduleIndex("app")];
    const app = wired[moduleIndex("app")] orelse
        fail("the app module's source file {s} is missing", .{app_spec.source_file});
    app.addImport("build_options", build_options_module);

    const exe = b.addExecutable(.{
        .name = "conduit",
        .root_module = app,
    });
    b.installArtifact(exe);
    installLinuxPayload(b, target, optimize);

    // The external driver CLI is a composition root rather than a product
    // module: it consumes the protocol and platform transport without becoming
    // an architectural dependency of the application.
    const conduit_test = b.createModule(.{
        .root_source_file = b.path("src/conduit_test.zig"),
        .target = target,
        .optimize = optimize,
    });
    conduit_test.addImport("platform", wired[moduleIndex("platform")].?);
    conduit_test.addImport("testdriver", wired[moduleIndex("testdriver")].?);
    conduit_test.addImport("build_options", build_options_module);
    const conduit_test_exe = b.addExecutable(.{
        .name = "conduit-test",
        .root_module = conduit_test,
    });
    b.installArtifact(conduit_test_exe);

    // TASK-25's runner is another composition root. It interacts only through
    // the installed conduit-test executable, so scenario code cannot acquire
    // an import edge into application state or accidentally bypass the driver.
    const e2e = b.createModule(.{
        .root_source_file = b.path("e2e/runner.zig"),
        .target = target,
        .optimize = optimize,
    });
    const e2e_exe = b.addExecutable(.{
        .name = "conduit-e2e",
        .root_module = e2e,
    });

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.step.dependOn(b.getInstallStep());
    if (b.args) |args| run_cmd.addArgs(args);
    b.step("run", "Run Conduit").dependOn(&run_cmd.step);

    const e2e_cmd = b.addRunArtifact(e2e_exe);
    e2e_cmd.step.dependOn(b.getInstallStep());
    e2e_cmd.addArg(b.getInstallPath(.bin, if (target.result.os.tag == .windows) "conduit-test.exe" else "conduit-test"));
    if (b.args) |args| e2e_cmd.addArgs(args);
    b.step("e2e", "Run the scripted end-to-end scenarios through conduit-test")
        .dependOn(&e2e_cmd.step);

    addTests(b, wired, conduit_test, e2e);
    try addBenchmarks(b, target, optimize, wired, exe, conduit_test_exe, build_options_module);

    if (font_wiring) |wiring| addFontCheck(b, target, optimize, wired[moduleIndex("font")].?, wiring);
}

/// The target `zig build` uses when no `-Dtarget` is given: the host, as usual,
/// except on a Windows host (TASK-5).
///
/// There a fully native target query makes Zig 0.16 compile every C and C++
/// source in the tree (Ghostty's wuffs and SIMD code, zlib, libpng, FreeType,
/// Oniguruma) into errors such as "argument unused during compilation:
/// '-fno-rtlib-defaultlib'" and vector types collapsing to scalars in
/// `mmintrin.h`. The same build succeeds on the same runner once the OS and ABI
/// are named, even with `-Dcpu=native` and the host's exact Windows version, so
/// only the native OS/ABI detection is avoided: the architecture and CPU stay
/// the host's, and the ABI is GNU, which is what native resolves to anyway.
fn defaultTargetQuery() std.Target.Query {
    if (builtin.os.tag != .windows) return .{};
    return .{
        .cpu_arch = builtin.cpu.arch,
        .cpu_model = .native,
        .os_tag = .windows,
        .abi = .gnu,
    };
}

/// Options for every `b.dependency("ghostty", ...)` call, so both resolve to one instance.
///
/// Left empty, Ghostty builds `ghostty-vt` in its own default Debug mode with
/// `slow_runtime_safety` on, which runs `Screen.assertIntegrity` and the page-list
/// integrity checks on every scroll: about 79 µs per linefeed inside a ReleaseSafe
/// Conduit and 1.5 ms inside a Debug one (TASK-72; `seq 1 200000` took 14.6 s in the
/// shipped v0.1.x binaries). The engine is therefore always built at least
/// ReleaseSafe. A Debug Conduit keeps its own safety checks and tests; it only gives
/// up Ghostty's internal integrity asserts, which Conduit's terminal tests do not
/// rely on.
fn ghosttyDependencyOptions(
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) struct { target: std.Build.ResolvedTarget, optimize: std.builtin.OptimizeMode } {
    return .{
        .target = target,
        .optimize = if (optimize == .Debug) .ReleaseSafe else optimize,
    };
}

/// The version a development build reports when no `-Dversion=` is given. It
/// is a valid SemVer prerelease on purpose, so every build passes the same
/// check a tagged release does.
const default_version = "0.0.0-dev";

/// Resolve `-Dversion=` and refuse anything that is not a SemVer 2.0.0 version
/// (`<major>.<minor>.<patch>[-prerelease][+build]`, no leading `v`). The release
/// workflow passes the tag with its `v` stripped, so the binary reports exactly
/// the tag it was built from; a typo fails configuration instead of shipping.
fn resolveVersion(b: *std.Build) [:0]const u8 {
    const raw = b.option(
        []const u8,
        "version",
        "Release version stamped into the binary (default 0.0.0-dev)",
    ) orelse default_version;
    _ = std.SemanticVersion.parse(raw) catch |err| fail(
        "-Dversion='{s}' is not a SemVer 2.0.0 version: expected " ++
            "<major>.<minor>.<patch>[-prerelease][+build] without a leading 'v' ({s})",
        .{ raw, @errorName(err) },
    );
    return b.allocator.dupeZ(u8, raw) catch @panic("OOM");
}

/// Stage the freedesktop metadata and redistributable runtime resources that
/// Linux packages install below their prefix. Other targets retain the exact
/// artifact-only install graph they had before this payload existed.
fn installLinuxPayload(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) void {
    if (target.result.os.tag != .linux) return;

    const desktop_source = b.path("assets/linux/io.github.thowd22.Conduit.desktop");
    const desktop_check = b.addCheckFile(desktop_source, .{ .expected_matches = &.{
        "Type=Application",
        "Exec=conduit",
        "Icon=io.github.thowd22.Conduit",
        "Terminal=false",
        "StartupWMClass=io.github.thowd22.Conduit",
    } });
    desktop_check.setName("validate the Linux desktop entry identity");
    installLinuxFileChecked(
        b,
        desktop_source,
        "share/applications/io.github.thowd22.Conduit.desktop",
        &desktop_check.step,
    );

    // The application icon, rendered from the checked-in master at every
    // freedesktop hicolor size a launcher or task switcher asks for. Each copy
    // is checked to be a PNG whose IHDR declares exactly its directory's size,
    // so a mis-rendered or swapped file fails the build instead of shipping.
    for (linux_icon_sizes) |size| {
        const source = b.path(b.fmt("assets/linux/icons/hicolor/{d}x{d}/apps/io.github.thowd22.Conduit.png", .{ size, size }));
        const check = b.addCheckFile(source, .{ .expected_matches = &.{pngHeader(b, size)} });
        check.setName(b.fmt("validate the Linux {d}x{d} icon", .{ size, size }));
        installLinuxFileChecked(
            b,
            source,
            b.fmt("share/icons/hicolor/{d}x{d}/apps/io.github.thowd22.Conduit.png", .{ size, size }),
            &check.step,
        );
    }

    const payload_files = [_]struct { source: std.Build.LazyPath, destination: []const u8 }{
        .{ .source = b.path(bundled_face_asset), .destination = "share/conduit/fonts/JetBrainsMono-Regular.ttf" },
        .{ .source = b.path("assets/shell-integration/bash/conduit.bash"), .destination = "share/conduit/shell-integration/bash/conduit.bash" },
        .{ .source = b.path("assets/shell-integration/zsh/.zshenv"), .destination = "share/conduit/shell-integration/zsh/.zshenv" },
        .{ .source = b.path("assets/shell-integration/zsh/conduit.zsh"), .destination = "share/conduit/shell-integration/zsh/conduit.zsh" },
        .{ .source = b.path("assets/shell-integration/fish/vendor_conf.d/conduit.fish"), .destination = "share/conduit/shell-integration/fish/vendor_conf.d/conduit.fish" },
        .{ .source = b.path("assets/fonts/LICENSE-JetBrainsMono-OFL-1.1.txt"), .destination = "share/licenses/conduit/JetBrainsMono-OFL-1.1.txt" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/FreeType-FTL.txt"), .destination = "share/licenses/conduit/FreeType-FTL.txt" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/FreeType-LICENSE.TXT"), .destination = "share/licenses/conduit/FreeType-LICENSE.TXT" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/HarfBuzz-COPYING.txt"), .destination = "share/licenses/conduit/HarfBuzz-COPYING.txt" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/Oniguruma-COPYING.txt"), .destination = "share/licenses/conduit/Oniguruma-COPYING.txt" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/zlib-LICENSE.txt"), .destination = "share/licenses/conduit/zlib-LICENSE.txt" },
        .{ .source = b.path("assets/THIRD-PARTY-LICENSES/libpng-LICENSE.txt"), .destination = "share/licenses/conduit/libpng-LICENSE.txt" },
        .{ .source = b.path("assets/fonts/LICENSE-NerdFonts.txt"), .destination = "share/licenses/conduit/NerdFonts-LICENSE.txt" },
        .{ .source = b.path("assets/fonts/NerdFonts-license-audit.md"), .destination = "share/licenses/conduit/NerdFonts-license-audit.md" },
        .{ .source = b.path("LICENSE"), .destination = "share/licenses/conduit/LICENSE" },
        .{ .source = b.dependency("ghostty", ghosttyDependencyOptions(target, optimize)).path("LICENSE"), .destination = "share/licenses/conduit/Ghostty-LICENSE" },
        .{ .source = b.dependency("sdl", .{ .target = target, .optimize = optimize }).path("LICENSE.txt"), .destination = "share/licenses/conduit/SDL-LICENSE.txt" },
        .{ .source = b.dependency("zopengl", .{}).path("LICENSE"), .destination = "share/licenses/conduit/zopengl-LICENSE" },
    };
    for (payload_files) |file| {
        b.getInstallStep().dependOn(&b.addInstallFile(file.source, file.destination).step);
    }
}

/// The freedesktop hicolor sizes the Linux payload installs the application
/// icon at. Each has a checked-in render under `assets/linux/icons/hicolor`.
const linux_icon_sizes = [_]u32{ 16, 22, 24, 32, 48, 64, 128, 256, 512 };

/// The first 24 bytes of a square `size`x`size` PNG: the signature, then the
/// IHDR chunk's length, type, width and height (big-endian). `addCheckFile`
/// only tests for substrings, not prefixes, but the PNG specification puts
/// IHDR immediately after the signature, so finding this run proves both the
/// format and the declared dimensions.
fn pngHeader(b: *std.Build, size: u32) []const u8 {
    var header: [24]u8 = undefined;
    @memcpy(header[0..8], "\x89PNG\r\n\x1a\n");
    std.mem.writeInt(u32, header[8..12], 13, .big);
    @memcpy(header[12..16], "IHDR");
    std.mem.writeInt(u32, header[16..20], size, .big);
    std.mem.writeInt(u32, header[20..24], size, .big);
    return b.allocator.dupe(u8, &header) catch @panic("OOM");
}

fn installLinuxFileChecked(
    b: *std.Build,
    source: std.Build.LazyPath,
    destination: []const u8,
    check: *std.Build.Step,
) void {
    const install = b.addInstallFile(source, destination);
    install.step.dependOn(check);
    b.getInstallStep().dependOn(&install.step);
}

/// Create one build module per Conduit module that has a source file, and point
/// each at the modules it may import. A dependency edge to a module that is not
/// written yet is left unwired: when that module's file lands, the edge comes
/// with it, and until then nothing can `@import` it, so a module that reaches for
/// it fails to compile rather than silently losing the import.
fn wireConduitModules(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) WiredModules {
    var wired: WiredModules = @splat(null);
    for (modules, 0..) |spec, i| {
        if (!sourceExists(b, spec.source_file)) continue;
        wired[i] = b.createModule(.{
            .root_source_file = b.path(spec.source_file),
            .target = target,
            .optimize = optimize,
        });
    }
    for (modules, 0..) |spec, i| {
        const mod = wired[i] orelse continue;
        for (spec.deps) |dep| {
            const dep_mod = wired[moduleIndex(dep)] orelse continue;
            mod.addImport(dep, dep_mod);
        }
    }
    return wired;
}

/// Attach the pinned third-party seams to the Conduit module that owns them:
/// SDL3 and its translated headers behind `platform`, OpenGL behind `render`,
/// and libghostty's terminal engine behind `term`.
///
/// The dependencies are resolved whether or not the module that owns a seam
/// exists yet, so a pin that does not resolve fails the build here instead of in
/// whichever task first imports it. The seams themselves attach only once their
/// module does, which keeps a seam from compiling a library nothing imports.
fn wireThirdPartySeams(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    wired: *const WiredModules,
) !?FontWiring {
    // Backlog decision-1: the terminal engine is the Zig module `ghostty-vt`,
    // never the macOS embedding library.
    const ghostty_vt = b.dependency("ghostty", ghosttyDependencyOptions(target, optimize)).module("ghostty-vt");
    if (wired[moduleIndex("term")]) |term| {
        term.addImport("ghostty-vt", ghostty_vt);

        // Backlog decision-4: exact Ghostty-pinned Oniguruma 6.9.9, built
        // statically and exposed only through Conduit's translated header.
        const oniguruma = try onigurumaLib(b, target, optimize);
        term.addImport("oniguruma-c", onigurumaSeam(b, target, optimize));
        term.linkLibrary(oniguruma);
        term.link_libc = true;
    }

    // Backlog decision-2: OpenGL 3.3 core, resolved through zopengl.
    const zopengl = b.dependency("zopengl", .{}).module("root");
    if (wired[moduleIndex("render")]) |render| render.addImport("zopengl", zopengl);

    // Backlog decision-2: SDL3 for window and input, through the `castholm/SDL`
    // build package plus a thin extern seam Conduit owns.
    const sdl_lib = sdlLib(b, target, optimize);
    if (wired[moduleIndex("platform")]) |platform| {
        platform.addImport("sdl", sdlSeam(b, target, optimize, sdl_lib));
        platform.linkLibrary(sdl_lib);

        // The window icon, as raw 64x64 RGBA8 pixels handed to SDL so task
        // switchers show it before any desktop entry is consulted. Embedded the
        // same way as the bundled face, because `@embedFile` may not reach
        // outside the module's package path.
        if (!sourceExists(b, window_icon_asset)) {
            fail("the window icon {s} is missing from the repository", .{window_icon_asset});
        }
        const icon_files = b.addWriteFiles();
        _ = icon_files.addCopyFile(b.path(window_icon_asset), "window_icon.rgba");
        platform.addAnonymousImport("window-icon", .{
            .root_source_file = icon_files.add("window_icon.zig",
                \\pub const rgba: []const u8 = @embedFile("window_icon.rgba");
            ),
        });
    }

    // The shell-integration scripts, embedded so a shell can be given them
    // without the repository being present at runtime. Same shape as the
    // bundled face: copied into a generated directory beside a Zig file that
    // `@embedFile`s them, because `@embedFile` may not reach outside a module's
    // package path. A missing script fails the build rather than shipping a
    // shell integration with a hole in it.
    if (wired[moduleIndex("app")]) |app| {
        const generated = b.addWriteFiles();
        for (shell_integration_assets) |asset| {
            if (!sourceExists(b, asset.source)) {
                fail("the shell integration script {s} is missing from the repository", .{asset.source});
            }
            _ = generated.addCopyFile(b.path(asset.source), asset.name);
        }
        app.addAnonymousImport("shell-integration", .{
            .root_source_file = generated.add("shell_integration.zig",
                \\pub const bash: []const u8 = @embedFile("conduit.bash");
                \\pub const zsh_env: []const u8 = @embedFile("zshenv");
                \\pub const zsh: []const u8 = @embedFile("conduit.zsh");
                \\pub const fish: []const u8 = @embedFile("conduit.fish");
            ),
        });
    }

    // The font manager: vendored FreeType and HarfBuzz behind the same kind
    // of seam SDL3 gets. FreeType rasterises, HarfBuzz shapes; both are
    // pinned in `build.zig.zon` and built from source because CI installs no
    // system packages.
    if (wired[moduleIndex("font")]) |font| return try wireFontSeams(b, target, optimize, font);
    return null;
}

/// What the font seam consists of, once it has been wired: the two vendored
/// libraries and the one translated module both `font` and the `font-check` step
/// use. They are returned rather than rebuilt per caller, so a second step
/// exercises the same artifacts instead of building its own copies.
const FontWiring = struct {
    freetype: *std.Build.Step.Compile,
    harfbuzz: *std.Build.Step.Compile,
    seam: *std.Build.Module,
};

/// The pinned SDL3 library artifact. Resolved even when no module imports it
/// yet, so the pin is exercised on every configure rather than first use.
fn sdlLib(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Step.Compile {
    return b.dependency("sdl", .{ .target = target, .optimize = optimize }).artifact("SDL3");
}

/// The Conduit-owned SDL3 seam: SDL's public headers, translated to Zig.
fn sdlSeam(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    sdl_lib: *std.Build.Step.Compile,
) *std.Build.Module {
    const seam = std.Build.Step.TranslateC.create(b, .{
        .root_source_file = b.addWriteFiles().add("sdl3.h", sdl_c_header),
        .target = target,
        .optimize = optimize,
    });
    seam.addIncludePath(sdl_lib.getEmittedIncludeTree());
    return seam.createModule();
}

/// Attach FreeType and HarfBuzz to the font manager: the vendored libraries,
/// and a Conduit-owned seam over each set of headers. This is the same shape
/// as the SDL3 seam — a built library plus translated headers — because the
/// font manager needs exactly what the platform module needs, from a source
/// that resolves the same way on every runner.
fn wireFontSeams(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    font: *std.Build.Module,
) !FontWiring {
    const ft_lib = try freetypeLib(b, target, optimize);
    const hb_lib = try harfbuzzLib(b, target, optimize, ft_lib);

    const font_c = fontSeam(b, target, optimize);
    font.addImport("font-c", font_c);
    font.linkLibrary(ft_lib);
    font.linkLibrary(hb_lib);

    // The bundled fallback face. `@embedFile` may not reach outside the
    // module's own package path, so the asset is copied into the generated
    // directory next to a one-line Zig file that embeds it: that file is the
    // module `font.zig` imports as `bundled-face`.
    const generated = b.addWriteFiles();
    if (!sourceExists(b, bundled_face_asset)) {
        fail("the bundled fallback font {s} is missing from the repository", .{bundled_face_asset});
    }
    _ = generated.addCopyFile(b.path(bundled_face_asset), bundled_face_name);
    font.addAnonymousImport("bundled-face", .{
        .root_source_file = generated.add("bundled_face.zig",
            \\pub const data: []const u8 = @embedFile("JetBrainsMono-Regular.ttf");
        ),
    });

    // The bundled Nerd Font symbols face (TASK-39): the last font-backed link
    // of every fallback chain, so private-use icons draw without a patched
    // font installed. Embedded for the same reason as the face above.
    if (!sourceExists(b, bundled_symbols_asset)) {
        fail("the bundled symbols font {s} is missing from the repository", .{bundled_symbols_asset});
    }
    _ = generated.addCopyFile(b.path(bundled_symbols_asset), bundled_symbols_name);
    font.addAnonymousImport("bundled-symbols", .{
        .root_source_file = generated.add("bundled_symbols.zig",
            \\pub const data: []const u8 = @embedFile("SymbolsNerdFontMono-Regular.ttf");
        ),
    });

    // FreeType is C and HarfBuzz is C++, so anything that links them links
    // both runtimes. They are set on the module rather than left to the
    // compilation because `font` is imported by `ui`, `app` and the test
    // binary, and only the root module of a compilation carries these.
    font.link_libc = true;
    // MSVC cannot mix Zig's bundled libc++ headers with the SDK's, which is
    // why the vendored HarfBuzz is built without libc++ there (see
    // `harfbuzzLib`).
    font.link_libcpp = if (target.result.abi == .msvc) null else true;

    return .{ .freetype = ft_lib, .harfbuzz = hb_lib, .seam = font_c };
}

